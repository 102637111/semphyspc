"""
ModelNet40RGB Dataset - fast loading from pre-computed .npz files.

Pre-computed files (generated by scripts/precompute_rgb_dataset.py):
    data/ModelNet/modelnet40_colored_processed/train.npz
    data/ModelNet/modelnet40_colored_processed/test.npz

Each .npz contains:
    points: [N, 1024, 6] float32 (XYZ + RGB, already FPS'd and normalized)
    labels: [N] int64
"""

import os
import numpy as np
import torch
from torch.utils.data import Dataset
from .build import DATASETS
from utils.logger import *


@DATASETS.register_module()
class ModelNet40RGB(Dataset):
    """
    Fast ModelNet40 dataset with pre-computed RGB point clouds.
    Loads from compressed .npz files — instant init, zero preprocessing.
    """

    def __init__(self, config):
        self.npoints = config.N_POINTS
        self.subset = config.subset

        # Path to pre-processed data
        processed_dir = (getattr(config, 'PROCESSED_DIR', None) or
                         'data/ModelNet/modelnet40_colored_processed')
        npz_path = os.path.join(processed_dir, f'{self.subset}.npz')

        if not os.path.exists(npz_path):
            raise FileNotFoundError(
                f'Pre-processed data not found: {npz_path}\n'
                f'Run: python scripts/precompute_rgb_dataset.py'
            )

        print_log(f'[ModelNet40RGB] Loading {npz_path}...', logger='ModelNet40RGB')
        data = np.load(npz_path)
        self.points = data['points']   # [N, 1024, 6]
        self.labels = data['labels']    # [N]
        print_log(f'[ModelNet40RGB] {self.subset}: {len(self)} samples, '
                  f'shape={self.points.shape}', logger='ModelNet40RGB')

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, index):
        pts = self.points[index].copy()

        # Shuffle for training augmentation
        if self.subset == 'train':
            pt_idxs = np.random.permutation(pts.shape[0])
            pts = pts[pt_idxs]

        pts_tensor = torch.from_numpy(pts).float()
        label = int(self.labels[index])

        return 'ModelNet40RGB', 'sample', (pts_tensor, label)
